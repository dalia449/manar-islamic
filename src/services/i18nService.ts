export class I18nService {
  private currentLanguage: LanguageCode = 'ar';

  constructor() {
    const saved = localStorage.getItem('manar_language') as LanguageCode;
    if (saved && TRANSLATIONS[saved]) {
      this.currentLanguage = saved;
    }
    this.updateDocumentDirection();
  }

  getLanguage(): LanguageCode {
    return this.currentLanguage;
  }

  setLanguage(code: LanguageCode) {
    if (TRANSLATIONS[code]) {
      this.currentLanguage = code;
      localStorage.setItem('manar_language', code);
      this.updateDocumentDirection();
    }
  }

  t(key: string): string {
    const dict = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS.ar;
    return dict[key] || TRANSLATIONS.en[key] || key;
  }

  getDirection(): 'rtl' | 'ltr' {
    return (this.currentLanguage === 'ar' || this.currentLanguage === 'ur') ? 'rtl' : 'ltr';
  }

  private updateDocumentDirection() {
    if (typeof document !== 'undefined') {
      const dir = this.getDirection();
      document.documentElement.dir = dir;
      document.documentElement.lang = this.currentLanguage;
    }
  }
}

export const i18n = new I18nService();
